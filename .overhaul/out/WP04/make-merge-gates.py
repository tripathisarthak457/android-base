"""Writes gates-merge.toml: WP04's merge acceptance (run 22 decision, handoff "Decisions").

The template's gates.toml stays the release gate and is not changed. For WP04's merge, the rows escalated in runs
15-16 (Part D 17b) are held as non-regression ratchets at the last full phone measurement before the final run,
plus 10 % (at least 0.1 percentage points for janky shares), as CP1 section 7 did for the pop rows; standard's app
PSS is held at the phase 3c tree measured again on Oct 18 (ab-standard-measure.win.sh), because the phone and the
tools moved it by more than the code did (41.7 MB on Oct 13, 46.5 MB on Oct 18 for the same tree); every other row
keeps its release limit. Two rows are added that the release gate does not have: the tab switch's janky frames
other than each switch's first, the share the first-frame escalation says is the motion itself.

    python3 make-merge-gates.py <template gates.toml> <out gates-merge.toml>
"""
import math
import sys
import tomllib

# metric -> {column: (last measured median, where it was measured)}
RATCHETS = {
    "tabs.janky_pct": {"solid": (1.15, "phase3c"), "standard": (1.15, "phase3c-standard")},
    "tabs_tap.janky_pct": {"solid": (1.15, "phase3c")},
    "pushpop.p99_ms": {"solid": (32, "phase3e"), "standard": (27, "phase3c-standard"), "lean": (28, "phase3d-lean")},
    "pushpop.janky_pct": {"lean": (2.24, "phase3d-lean")},
    "pushpop_gesture.janky_pct": {"solid": (2.33, "phase3e")},
    "scroll_root.janky_pct": {"solid": (0.88, "phase3c"), "standard": (0.52, "phase3c-standard")},
    "scroll_minimize.janky_pct": {"solid": (0.89, "phase3c")},
    "coldstart.median_ms": {"solid": (390, "phase3c")},
    "coldstart_installed.median_ms": {"solid": (419, "phase3c")},
    "meminfo.pss_app_mb": {"solid": (53.6, "phase3c"), "standard": (46.5, "d10ef94 remeasured Oct 18")},
}

ADDED = [
    {"metric": "tabs.janky_after_first_pct", "solid": 0.1, "standard": 0.1, "lean": 0.1,
     "label": "Tab switch, janky frames other than each switch's first (%)"},
    {"metric": "tabs_tap.janky_after_first_pct", "solid": 0.1,
     "label": "Tab switch with plain taps, janky frames other than each switch's first (%)"},
]


def ratchet(metric, value):
    if metric.endswith("janky_pct"):
        return round(max(value * 1.1, value + 0.1), 2)
    if metric.endswith("_ms") and value >= 100:
        return math.ceil(value * 1.1)
    return round(value * 1.1, 1)


def toml_value(value):
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, str):
        return '"' + value.replace('"', '\\"') + '"'
    if isinstance(value, dict):
        return "{ " + ", ".join(f"{key} = {toml_value(item)}" for key, item in value.items()) + " }"
    return repr(value)


def main(source, target):
    with open(source, "rb") as handle:
        rows = tomllib.load(handle)["row"]
    out = ["# WP04 merge acceptance, generated by make-merge-gates.py from the template's gates.toml.",
           "# Release limits are unchanged in gates.toml; rows marked [merge ratchet] hold the last measured value.", ""]
    for row in rows + ADDED:
        row = dict(row)
        notes = []
        for column, (value, source_run) in RATCHETS.get(row["metric"], {}).items():
            if column in row:
                notes.append(f"{column} {row[column]} -> {ratchet(row['metric'], value)} ({source_run} {value})")
                row[column] = ratchet(row["metric"], value)
        if notes:
            row["label"] += " [merge ratchet; release limit " + "; ".join(notes) + "]"
        out.append("[[row]]")
        for key, value in row.items():
            out.append(f"{key} = {toml_value(value)}")
        out.append("")
    with open(target, "w", encoding="utf-8", newline="\n") as handle:
        handle.write("\n".join(out))
    with open(target, "rb") as handle:
        tomllib.load(handle)


if __name__ == "__main__":
    main(*sys.argv[1:])
