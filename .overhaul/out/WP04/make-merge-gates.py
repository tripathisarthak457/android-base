"""Writes gates-merge.toml: WP04's merge acceptance (run 22 decision, Deviation 28; since run 28, REQUIREMENTS 42).

Since REQUIREMENTS 42 the template's gates.toml holds the rows that were escalated before (total janky shares,
first frames, p99, app PSS) as non-regression rows of its own, so the merge gate is the release gate, except for the
release rows that the last full phone measurement fails: those are held where that measurement left them (its worst
run, plus 10 %), so the merge cannot make them worse while the work that brings them under their release limit is
still open (the back gesture's and Rapid Back's hitches, the installed cold start; handoff, run 28).

    python3 make-merge-gates.py <template gates.toml> <out gates-merge.toml>
"""
import math
import sys
import tomllib

# metric -> {column: (worst run of the last full measurement, where it was measured)}
RATCHETS = {
    "pushpop_gesture.hitch_ms_per_s": {"solid": (24.5, "run 26 f60c0c7")},
    "rapid_back.hitch_ms_per_s": {"solid": (18.33, "run 26 f60c0c7")},
    "coldstart_installed.median_ms": {"solid": (423, "run 26 f60c0c7")},
}


def ratchet(metric, value):
    if metric.endswith("janky_pct"):
        return round(max(value * 1.1, value + 0.1), 2)
    if metric.endswith("_ms") and value >= 100:
        return math.ceil(value * 1.1)
    return round(value * 1.1, 1)


def toml_value(value):
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, str):
        return '"' + value.replace('"', '\\"') + '"'
    if isinstance(value, dict):
        return "{ " + ", ".join(f"{key} = {toml_value(item)}" for key, item in value.items()) + " }"
    return repr(value)


def main(source, target):
    with open(source, "rb") as handle:
        rows = tomllib.load(handle)["row"]
    out = ["# WP04 merge acceptance, generated by make-merge-gates.py from the template's gates.toml.",
           "# The release gate, with the rows marked [merge hold] held where the last full measurement left them.", ""]
    for row in rows:
        row = dict(row)
        notes = []
        for column, (value, source_run) in RATCHETS.get(row["metric"], {}).items():
            if column in row:
                notes.append(f"{column} {row[column]} -> {ratchet(row['metric'], value)} ({source_run} {value})")
                row[column] = ratchet(row["metric"], value)
        if notes:
            row["label"] += " [merge hold; release limit " + "; ".join(notes) + "]"
        out.append("[[row]]")
        for key, value in row.items():
            out.append(f"{key} = {toml_value(value)}")
        out.append("")
    with open(target, "w", encoding="utf-8", newline="\n") as handle:
        handle.write("\n".join(out))
    with open(target, "rb") as handle:
        tomllib.load(handle)


if __name__ == "__main__":
    main(*sys.argv[1:])
