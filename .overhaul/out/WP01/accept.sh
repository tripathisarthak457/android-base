#!/usr/bin/env bash
set -euo pipefail
OV=/home/crazyhusir/Documents/projects/tools/.overhaul; W=$OV/wt/WP01; O=$OV/out/WP01
cd $W/generator
python3 -m unittest discover -s tests -t .                       # all pass; PyYAML-dependent tests may skip
python3 -m tests.consistency --quick                              # presets × compact, singles, pairwise: clean
python3 -m genkit.tokens --check
python3 -m genkit.core.catalogue --check                          # the checked-in website copy is current
python3 -m genkit.core.catalogue --json | python3 -m json.tool > /dev/null
for f in tests/fixtures/v1/*.json; do python3 create_project.py --spec $f --out $O/v1/$(basename $f .json) --no-zip --force; done
python3 generate_headless.py --target android $O/p.zip < tests/fixtures/v2/standard.json \
  | python3 -c 'import json,sys; d=json.load(sys.stdin); assert d["ok"] and d["zip_bytes"]>0'
set +e; echo '{"schema":2,"platform":"android","app_name":"x"}' | python3 generate_headless.py --target android $O/bad.zip > $O/bad.json; rc=$?; set -e
test $rc -eq 2
python3 -c 'import json,sys; d=json.load(open(sys.argv[1])); assert d["kind"]=="invalid"' $O/bad.json
python3 create_project.py --spec tests/fixtures/v2/standard.json --set package_name=com.example.wp01.std --dry-run --json \
  | python3 -c 'import json,sys; json.load(sys.stdin)'
test ! -e genkit/render.py
test ! -e genkit/readme.py
# set -e ignores a command negated with !, so a match has to fail the script explicitly.
if grep -rnE "import (render|readme)|from \.+(render|readme) " genkit; then exit 1; fi
# $O/before was generated by the untouched generator of overhaul/multiplatform-v2 at 54d078d (WP02-M1 merged);
# $O/before-6bc38e9 is the first baseline. Regenerate the other side from this tree.
bash $O/gen_all.sh $W/generator $O/after > /dev/null
python3 $O/golden_check.py $O/before $O/after $O/golden-allow.txt
echo ACCEPT OK
