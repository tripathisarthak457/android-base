"""
Generates the same specs with two checkouts of this repository and compares the projects file by file.

    python3 tools/compare_generations.py --before ../old --after .          # every file the same, or exit 1
    python3 tools/compare_generations.py --before ../old --after . --keep D  # keep both trees under D
    python3 tools/compare_generations.py --before ../old --after . --time 5  # also time five generations

A generator change that should leave existing projects alone is proven to, rather than assumed:
every spec in the set is generated by both checkouts' own `create_project.py`, from their own
templates, and every path present in either tree is compared byte for byte. Only the paths in
EXCEPTIONS may differ, each for a reason the change names; `generator-spec.json` is compared with
its provenance stamp (commit and date) taken out. A file present in one tree only is a difference.

`--spec-set DIR` reads the specs from DIR/*.json instead of the default set: every preset in both
architectures, no features and every feature, every feature with every language and with modules,
and the consistency matrix's hostile names.
"""

from __future__ import annotations

import argparse
import concurrent.futures
import difflib
import fnmatch
import json
import os
import shutil
import statistics
import subprocess
import sys
import tempfile
import time
from pathlib import Path

REPOSITORY = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(REPOSITORY / "generator"))

from genkit.core import translations  # noqa: E402
from genkit.core.record import RECORD_NAME  # noqa: E402
from genkit.core.spec import STAMP_KEY  # noqa: E402
from genkit.targets import get  # noqa: E402
from tests.consistency.__main__ import HOSTILE  # noqa: E402

#: Paths a project may change in without its spec changing, each with why. Every other path must
#: be byte-identical. `*` crosses directories, as in the manifest's globs.
EXCEPTIONS: dict[str, str] = {
    "CLAUDE.md": "the agent instructions and their index of the docs",
    "AGENTS.md": "the same instructions for agents that do not read CLAUDE.md",
    "README.md": "the README's line on effects and its pointer to the docs",
    "docs/*": "the architecture, performance and design-system guides",
    ".agents/skills/*": "the vendored Android skills",
    ".claude/skills/*": "the pointers to the vendored Android skills",
    "tools/android_skills.py": "the command that refreshes the vendored skills",
    "build-logic/convention/src/main/kotlin/*/buildlogic/guard/CodeRules.kt": (
        "the code rules' failure message, which names the docs that say why (only the message may change)"
    ),
}

#: An exception whose diff is printed even when it is allowed, for a reviewer to read.
REVIEWED = ("build-logic/convention/src/main/kotlin/*/buildlogic/guard/CodeRules.kt",)

PACKAGE = "com.example.compare"


def default_specs() -> dict[str, dict]:
    manifest = get("android").manifest
    every = sorted(feature.key for feature in manifest.selectable)
    languages = list(translations.available("android"))

    def spec(features, architecture="compact", **fields):
        return {
            "schema": 2, "platform": "android", "app_name": "Compare", "package_name": PACKAGE,
            "architecture": architecture, "features": sorted(features), **fields,
        }

    specs = {
        f"preset-{preset}-{architecture}": spec(manifest.preset_features(preset), architecture)
        for preset in manifest.presets
        for architecture in ("compact", "modular")
    }
    specs["none"] = spec([])
    specs["all"] = spec(every)
    specs["everything-languages"] = spec(every, languages=languages)
    specs["everything-modules"] = spec(every, feature_modules=["orders", "order_history"])
    for index, (app, package, modules) in enumerate(HOSTILE):
        specs[f"hostile-{index}"] = spec(every, app_name=app, package_name=package, feature_modules=list(modules))
    return specs


def read_specs(directory: Path) -> dict[str, dict]:
    return {path.stem: json.loads(path.read_text(encoding="utf-8")) for path in sorted(directory.glob("*.json"))}


def generate(checkout: Path, spec: dict, destination: Path) -> float:
    """Generates `spec` with `checkout`'s own generator; returns the seconds it took."""
    destination.parent.mkdir(parents=True, exist_ok=True)
    spec_file = destination.parent / f"{destination.name}.spec.json"
    spec_file.write_text(json.dumps(spec), encoding="utf-8")
    started = time.perf_counter()
    result = subprocess.run(
        [sys.executable, str(checkout / "generator" / "create_project.py"),
         "--spec", str(spec_file), "--out", str(destination), "--no-zip", "--json"],
        capture_output=True, text=True, encoding="utf-8", cwd=checkout / "generator", check=False,
    )
    elapsed = time.perf_counter() - started
    spec_file.unlink()
    if result.returncode != 0:
        raise RuntimeError(f"{checkout} failed on {destination.name}:\n{result.stdout}\n{result.stderr}")
    return elapsed


def files(root: Path) -> dict[str, Path]:
    return {path.relative_to(root).as_posix(): path for path in root.rglob("*") if path.is_file()}


def excepted(relative: str) -> str | None:
    return next((glob for glob in EXCEPTIONS if fnmatch.fnmatchcase(relative, glob)), None)


def without_stamp(path: Path) -> bytes:
    data = json.loads(path.read_text(encoding="utf-8"))
    data.pop(STAMP_KEY, None)
    return json.dumps(data, indent=2).encode("utf-8")


def compare(before: Path, after: Path) -> tuple[list[str], list[str]]:
    """(differences outside the exceptions, unified diffs of the reviewed exceptions)."""
    old, new = files(before), files(after)
    problems: list[str] = []
    reviewed: list[str] = []
    for relative in sorted(set(old) | set(new)):
        glob = excepted(relative)
        if relative not in old or relative not in new:
            if glob is None:
                problems.append(f"only in {'after' if relative in new else 'before'}: {relative}")
            continue
        if relative == RECORD_NAME:
            same = without_stamp(old[relative]) == without_stamp(new[relative])
        else:
            same = old[relative].read_bytes() == new[relative].read_bytes()
        if same:
            continue
        if glob is None:
            problems.append(f"differs: {relative}")
        elif glob in REVIEWED:
            reviewed.append("".join(difflib.unified_diff(
                old[relative].read_text(encoding="utf-8").splitlines(keepends=True),
                new[relative].read_text(encoding="utf-8").splitlines(keepends=True),
                f"before/{relative}", f"after/{relative}",
            )))
    return problems, reviewed


def run_one(name: str, spec: dict, before: Path, after: Path, work: Path) -> tuple[str, list[str], list[str]]:
    old, new = work / "before" / name, work / "after" / name
    generate(before, spec, old)
    generate(after, spec, new)
    problems, reviewed = compare(old, new)
    return name, problems, reviewed


def timing(before: Path, after: Path, work: Path, runs: int) -> None:
    every = default_specs()["all"]
    arms = {"before, UI": (before, every), "after, UI": (after, every)}
    if "ui_components" in get("android").manifest.options:
        arms["after, No UI"] = (after, {**every, "ui_components": False})
    seconds: dict[str, list[float]] = {arm: [] for arm in arms}
    # Arms take turns, so a machine that slows down over the run slows every arm alike.
    for index in range(runs):
        for arm, (checkout, spec) in arms.items():
            destination = work / "time" / f"{arm.replace(', ', '-').replace(' ', '')}-{index}"
            seconds[arm].append(generate(checkout, spec, destination))
            shutil.rmtree(destination)
    print(f"\nGeneration time, every feature, {runs} runs each (median, min-max):")
    for arm, values in seconds.items():
        print(f"  {arm:14} {statistics.median(values):6.2f} s  ({min(values):.2f}-{max(values):.2f})")


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(prog="compare_generations", description=__doc__.strip().splitlines()[0])
    parser.add_argument("--before", type=Path, required=True, help="the checkout to compare against")
    parser.add_argument("--after", type=Path, required=True, help="the checkout with the change")
    parser.add_argument("--spec-set", default="default", help="'default', or a directory of spec JSON files")
    parser.add_argument("--keep", type=Path, help="generate under this directory and keep the projects")
    parser.add_argument("--time", type=int, default=0, metavar="N", help="also time N generations of every feature")
    parser.add_argument("--jobs", type=int, default=min(4, os.cpu_count() or 1))
    args = parser.parse_args(argv)

    before, after = args.before.resolve(), args.after.resolve()
    for checkout in (before, after):
        if not (checkout / "generator" / "create_project.py").is_file():
            parser.error(f"{checkout} is not a checkout of this repository")
    specs = default_specs() if args.spec_set == "default" else read_specs(Path(args.spec_set))
    work = args.keep.resolve() if args.keep else Path(tempfile.mkdtemp(prefix="compare-"))
    work.mkdir(parents=True, exist_ok=True)

    failed = False
    try:
        with concurrent.futures.ProcessPoolExecutor(max_workers=args.jobs) as pool:
            futures = [pool.submit(run_one, name, spec, before, after, work) for name, spec in specs.items()]
            results = sorted(future.result() for future in concurrent.futures.as_completed(futures))
        shown: set[str] = set()
        for name, problems, reviewed in results:
            for problem in problems:
                print(f"{name}: {problem}")
            failed = failed or bool(problems)
            for diff in reviewed:
                if diff not in shown:
                    shown.add(diff)
                    print(f"\n{name}: allowed, for review:\n{diff}")
        if args.time:
            timing(before, after, work, args.time)
    finally:
        if args.keep is None:
            shutil.rmtree(work, ignore_errors=True)

    print(f"\n{len(specs)} specs, each generated by both checkouts: "
          + ("differences outside the exceptions." if failed else "identical outside the exceptions."))
    for glob, why in EXCEPTIONS.items():
        print(f"  allowed to differ: {glob} ({why})")
    return 1 if failed else 0


if __name__ == "__main__":
    sys.exit(main())
